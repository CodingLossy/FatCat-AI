// Writes version.js from the root package.json so the prototype shows the package version, not a typed-in number.
// Usage: node docs/design/prototype/sync-version.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../package.json', import.meta.url);
const { version } = JSON.parse(readFileSync(root, 'utf8'));
const out = new URL('./version.js', import.meta.url);
writeFileSync(
    out,
    `// SPDX-License-Identifier: AGPL-3.0-only\n// Copyright (C) 2026 尹绪柏 (Theodore Yin)\n\n// Generated by sync-version.mjs from the root package.json; do not edit.\nwindow.__PKG_VERSION__ = ${JSON.stringify(version)};\n`,
);
console.log(`version.js -> ${version}`);
